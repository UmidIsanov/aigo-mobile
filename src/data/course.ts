export const taskRefs: TaskRef[] = course.flatMap((m, mi) =>
  m.lessons.flatMap((l, li) => l.tasks.map((_, ti) => ({ id: taskId(mi, li, ti), module: mi, lesson: li, task: ti }))),
);

/** Where the student is: the explicit cursor, else the first unfinished task, else null (course done). */
export function currentTask(completed: string[], cursor: string | null): TaskRef | null {
  return taskRefs.find((r) => r.id === cursor) ?? taskRefs.find((r) => !completed.includes(r.id)) ?? null;
}

export function nextTask(id: string): TaskRef | null {
  const i = taskRefs.findIndex((r) => r.id === id);
  return i >= 0 ? (taskRefs[i + 1] ?? null) : null;
}
